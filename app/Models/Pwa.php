<?php

namespace App\Models;

use App\Enums\PwaStatus;
use Database\Factories\PwaFactory;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Str;

class Pwa extends Model
{
    /** @use HasFactory<PwaFactory> */
    use HasFactory, SoftDeletes;

    public const STATUS_DRAFT = 'draft';

    public const STATUS_PENDING = 'pending';

    public const STATUS_APPROVED = 'approved';

    public const STATUS_REJECTED = 'rejected';

    protected $fillable = [
        'category_id',
        'name',
        'slug',
        'short_description',
        'description',
        'manifest_url',
        'start_url',
        'icon_url',
        'screenshots',
        'version',
        'pricing_type',
        'price',
        'privacy_policy_url',
        'is_verified',
        'compatibility',
    ];

    protected function casts(): array
    {
        return [
            'status' => PwaStatus::class,
            'screenshots' => 'array',
            'compatibility' => 'array',
            'is_published' => 'boolean',
            'is_verified' => 'boolean',
            'price' => 'float',
            'install_count' => 'integer',
            'views_count' => 'integer',
            'clicks_count' => 'integer',
            'rating_average' => 'float',
            'review_count' => 'integer',
            'reviewed_at' => 'datetime',
        ];
    }

    public function getRouteKeyName(): string
    {
        return 'slug';
    }

    public bool $wasSlugAutogenerated = false;

    protected static function booted(): void
    {
        static::creating(function (Pwa $pwa): void {
            if (blank($pwa->slug)) {
                $pwa->wasSlugAutogenerated = true;
                $baseSlug = Str::slug($pwa->name) ?: 'pwa';
                $slug = $baseSlug;
                $counter = 1;
                while (static::withTrashed()->where('slug', $slug)->exists()) {
                    $slug = "{$baseSlug}-{$counter}";
                    $counter++;
                }
                $pwa->slug = $slug;
            }
        });
    }

    public function save(array $options = []): bool
    {
        if (! $this->exists && $this->wasSlugAutogenerated) {
            $attempts = 0;
            while (true) {
                try {
                    return parent::save($options);
                } catch (UniqueConstraintViolationException $e) {
                    $attempts++;
                    if ($attempts >= 5) {
                        throw $e;
                    }
                    $baseSlug = Str::slug($this->name) ?: 'pwa';
                    $this->slug = "{$baseSlug}-".Str::lower(Str::random(6));
                }
            }
        }

        return parent::save($options);
    }

    public function developer(): BelongsTo
    {
        return $this->belongsTo(User::class, 'developer_id');
    }

    public function category(): BelongsTo
    {
        return $this->belongsTo(Category::class);
    }

    public function reviewer(): BelongsTo
    {
        return $this->belongsTo(User::class, 'reviewed_by');
    }

    public function reviews(): HasMany
    {
        return $this->hasMany(Review::class);
    }

    public function installations(): HasMany
    {
        return $this->hasMany(Installation::class);
    }

    public function moderationLogs(): HasMany
    {
        return $this->hasMany(ModerationLog::class);
    }

    public function favorites(): HasMany
    {
        return $this->hasMany(Favorite::class);
    }

    public function analyticsEvents(): HasMany
    {
        return $this->hasMany(AnalyticsEvent::class);
    }

    public function scopePublished(Builder $query): Builder
    {
        return $query->where('status', self::STATUS_APPROVED)
            ->where('is_published', true);
    }

    public function scopePending(Builder $query): Builder
    {
        return $query->where('status', self::STATUS_PENDING);
    }

    public function scopeSearch(Builder $query, ?string $term): Builder
    {
        if (blank($term)) {
            return $query;
        }

        return $query->where(function (Builder $q) use ($term): void {
            $q->where('name', 'like', "%{$term}%")
                ->orWhere('short_description', 'like', "%{$term}%");
        });
    }
}
