<?php

namespace App\Providers;

use App\Models\Pwa;
use App\Models\Review;
use App\Policies\PwaPolicy;
use App\Policies\ReviewPolicy;
use Illuminate\Cache\RateLimiting\Limit;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\RateLimiter;
use Illuminate\Support\ServiceProvider;
use Illuminate\Support\Str;

class AppServiceProvider extends ServiceProvider
{
    /**
     * Register any application services.
     */
    public function register(): void
    {
        //
    }

    /**
     * Bootstrap any application services.
     */
    public function boot(): void
    {
        // Explicit policy registration
        Gate::policy(Pwa::class, PwaPolicy::class);
        Gate::policy(Review::class, ReviewPolicy::class);

        // Rate Limiters
        RateLimiter::for('login', function (Request $request) {
            $rawLogin = $request->input('login');
            $login = is_string($rawLogin) ? $rawLogin : '';
            $throttleKey = Str::transliterate(Str::lower($login).'|'.$request->ip());

            return Limit::perMinute(5)->by($throttleKey);
        });

        RateLimiter::for('register', function (Request $request) {
            return Limit::perMinute(5)->by($request->ip());
        });

        RateLimiter::for('api', function (Request $request) {
            return Limit::perMinute(60)->by($request->user()?->id ?: $request->ip());
        });

        RateLimiter::for('write', function (Request $request) {
            return Limit::perMinute(30)->by($request->user()?->id ?: $request->ip());
        });
    }
}
